'use strict';
const assert=require('node:assert/strict');
const E=require('../v3/engine').V3Engine,C=require('../v3/curriculum').V3Curriculum;
const combination=['fox','forestbg','cap','hoodie'];
const s=E.fresh();s.bought=[...combination,'dog','crown','wings','glasses','watch'];s.coins=17;
const preserved=JSON.stringify({bought:s.bought,coins:s.coins,earned:s.earned});
for(const id of combination)assert(E.purchase(s,id,C.catalog));
assert.deepEqual(s.equipped,combination);
assert.deepEqual(E.migrate(JSON.parse(JSON.stringify(s))).equipped,combination);
E.purchase(s,'dog',C.catalog);assert.deepEqual(s.equipped,['forestbg','cap','hoodie','dog']);
E.removeEquipment(s,'Headwear');assert.deepEqual(s.equipped,['forestbg','hoodie','dog']);
assert.equal(JSON.stringify({bought:s.bought,coins:s.coins,earned:s.earned}),preserved);
for(const id of combination)assert.deepEqual(E.migrate({bought:[id],equipped:id}).equipped,[id]);
assert.deepEqual(E.migrate({bought:combination,equipped:combination}).equipped,combination);
assert.deepEqual(E.migrate({equipped:['cap','fox','crown','forestbg','hoodie']}).equipped,['fox','crown','forestbg','hoodie']);
assert.deepEqual(E.migrate({equipped:['cap','crown','cap']}).equipped,['cap']);
assert.deepEqual(E.migrate({equipped:['watch','unknown-old-id']}).equipped,['watch','unknown-old-id']);
for(const value of [null,{},27])assert.deepEqual(E.migrate({equipped:value}).equipped,[]);
const six=E.fresh();six.bought=[...combination,'wings','glasses'];
for(const id of six.bought)assert(E.purchase(six,id,C.catalog));
assert.deepEqual(six.equipped,six.bought);
E.removeEquipment(six,'Back items');assert.deepEqual(six.equipped,[...combination,'glasses']);
E.purchase(six,'glasses',C.catalog);assert.deepEqual(six.equipped,combination);
const older={bought:[...combination,'watch'],equipped:[...combination,'watch'],coins:29,unrecognised:{keep:true}};
const original=JSON.stringify(older),migrated=E.migrate(older);
assert.equal(JSON.stringify(older),original);for(const field of ['bought','equipped','coins','unrecognised'])assert.deepEqual(migrated[field],older[field]);
assert.deepEqual(E.migrate(migrated),migrated);
const empty=E.fresh();assert.equal(E.purchase(empty,'crown',C.catalog),false);assert.deepEqual(empty.bought,[]);assert.equal(empty.coins,0);
assert.equal(E.removeEquipment(s,'invalid'),false);
console.log('PASS equipment combinations, independent replacement/removal, JSON reload, legacy array/single item, unknown/retired preservation and unchanged ownership/wallet');
